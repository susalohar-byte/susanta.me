// Regenerates migrations/0002_seed.sql from scripts/content.json (the site's starting content).
// Run: node scripts/seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const C = JSON.parse(readFileSync(join(root, 'scripts/content.json'), 'utf8'));
const q = (v) => `'${String(v ?? '').replace(/'/g, "''")}'`;
const lines = ['-- Starting content, generated by scripts/seed.mjs. Edit later from /admin.'];

for (const [k, v] of Object.entries(C.settings)) lines.push(`INSERT OR IGNORE INTO settings (key, value) VALUES (${q(k)}, ${q(v)});`);
for (const p of C.projects) {
  lines.push(`INSERT OR IGNORE INTO projects (slug, title, category, category_label, location, image, url, highlight, challenge, solution, metrics, sort, published) VALUES (${[
    p.slug, p.title, p.category, p.category_label, p.location, p.image, p.url || '', p.highlight, p.challenge, p.solution, JSON.stringify(p.metrics)].map(q).join(', ')}, ${Number(p.sort) || 0}, ${p.published ? 1 : 0});`);
}
for (const r of C.reviews) {
  lines.push(`INSERT INTO reviews (name, role, result, quote, rating, sort, published) SELECT ${[r.name, r.role, r.result, r.quote].map(q).join(', ')}, ${Number(r.rating) || 5}, ${Number(r.sort) || 0}, ${r.published ? 1 : 0} WHERE NOT EXISTS (SELECT 1 FROM reviews WHERE name = ${q(r.name)});`);
}
for (const p of C.posts) {
  lines.push(`INSERT OR IGNORE INTO posts (slug, title, excerpt, category, cover_image, content, published, published_at) VALUES (${[
    p.slug, p.title, p.excerpt, p.category, p.cover_image, p.content].map(q).join(', ')}, ${p.published ? 1 : 0}, ${q(p.published_at)});`);
}
writeFileSync(join(root, 'migrations/0002_seed.sql'), `${lines.join('\n')}\n`);

// Plans + FAQs live in their own migration (tables are created in 0004).
const extra = ['-- Starting plans & FAQs, generated by scripts/seed.mjs. Edit later from /admin.'];
for (const p of C.plans) {
  extra.push(`INSERT INTO plans (name, badge, price, period, description, features, cta, popular, sort, published) SELECT ${[
    p.name, p.badge, p.price, p.period, p.description, JSON.stringify(p.features), p.cta].map(q).join(', ')}, ${p.popular ? 1 : 0}, ${Number(p.sort) || 0}, ${p.published ? 1 : 0} WHERE NOT EXISTS (SELECT 1 FROM plans WHERE name = ${q(p.name)});`);
}
for (const f of C.faqs) {
  extra.push(`INSERT INTO faqs (category, question, answer, show_on_home, sort, published) SELECT ${[f.category, f.question, f.answer].map(q).join(', ')}, ${f.show_on_home ? 1 : 0}, ${Number(f.sort) || 0}, ${f.published ? 1 : 0} WHERE NOT EXISTS (SELECT 1 FROM faqs WHERE question = ${q(f.question)});`);
}
writeFileSync(join(root, 'migrations/0005_seed_plans_faqs.sql'), `${extra.join('\n')}\n`);
console.log(`Wrote ${lines.length - 1} statements to 0002_seed.sql and ${extra.length - 1} to 0005_seed_plans_faqs.sql`);
